/**
 * Cuts the owner's spiral glass into the row's SEARCH mark.
 *
 *   npm run build:searchglyph
 *
 * The owner's 2026-09-19 ask: "turn this image into a magnifying glass icon
 * that is the same style as the + button. Make it the same size". The image
 * (scripts/assets/search-glass.jpg) is a disc with three spirals cut out of it
 * and a curling tail — a magnifying glass already, lens and handle — so what
 * "turn it into an icon" means is what it meant for the plus and the minus:
 * a vector that can be DRAWN INLINE AND FILLED WITH currentColor, because the
 * button it sits in inverts under the pointer and an <img> cannot follow it
 * (lib/cigToggleGlyph.ts says the same of the other two).
 *
 * The tracing is scripts/lib/trace-mark.mjs, shared with the dots. Two things
 * are this mark's own:
 *
 * THE WHITE IS OPENED UP BEFORE TRACING (`OPEN`). The spirals' cuts are about
 * 3% of the mark's width — a third of a pixel at the size the row draws it —
 * and a browser antialiases a cut that thin into grey, so the lens arrives as a
 * mottled disc. Taking a little off the black widens the cuts so that they
 * survive the reduction, the same reason the 發 tile is sharpened per density.
 * What comes through at 21px is a ring with a pale three-armed centre,
 * which reads as a lens — and the plus beside it is a pinwheel too.
 *
 * THE HANDLE IS CUT SHORT (`HANDLE`, the owner's 2026-09-20 "make it so the
 * magnifying glass has a shorter handle so it can be more evenly situated
 * relative to the outline"). As drawn the tail runs to 2.6 lens radii, which
 * makes the mark a third wider than tall with the lens pushed up into one
 * corner of its box; cut at 1.75 the mark is nearly square, and its ink's
 * centre of mass is the box's centre to within a tenth of a unit. The cut is
 * an arc about the lens's centre, so the handle ends square to its own
 * direction.
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import sharp from 'sharp';
import { inkMask, erode, contours, loopArea, simplify, toPath } from './lib/trace-mark.mjs';

const SRC = 'scripts/assets/search-glass.jpg';
const OUT = 'lib/searchGlyph.ts';

/** The trace's own resolution: the mark's long side, in px. */
const TRACE = 1200;
/** How much black comes off every edge before tracing, in trace px. */
const OPEN = Number(process.env.GLYPH_OPEN ?? 12);
/** How much of the handle is kept, as a reach from the lens's centre in radii. */
const HANDLE = Number(process.env.GLYPH_HANDLE ?? 1.75);
/** The mark's long side as drawn, in the button's px: the plus's own 16. */
const MARK = 16;
/** Douglas-Peucker tolerance, in trace px. */
const EPS = 1.6;
/** Loops smaller than this are jpeg speckle, not drawing (trace px of area). */
const MIN_AREA = 60;

const fail = (m) => {
  throw new Error(`build-search-glyph: ${m}`);
};

const m = await inkMask(SRC, { trace: TRACE, pad: OPEN + 4 });
console.log(`${SRC}: ${m.source}, traced at ${m.W0}x${m.H0}`);

// THE LENS is the disc that touches the picture's left and top edges: its
// centre is level with the middle of the ink on the left edge and under the
// middle of the ink on the top edge, and its radius is the distance to either.
{
  const edge = (pick) => {
    let a = 1e9, b = -1;
    const n = pick === 'x' ? m.W0 : m.H0;
    for (let t = 0; t < n; t++) {
      const on = pick === 'x' ? m.grey[2 * m.W0 + t] < 128 : m.grey[t * m.W0 + 2] < 128;
      if (on) { a = Math.min(a, t); b = Math.max(b, t); }
    }
    return (a + b) / 2;
  };
  const cx = edge('x'), cy = edge('y');
  const R = (cx + cy) / 2;
  if (!(R > m.W0 * 0.2 && R < m.W0 * 0.45)) fail(`the lens was not found where it should be (centre ${cx},${cy})`);
  let cut = 0;
  for (let y = 0; y < m.H0; y++) for (let x = 0; x < m.W0; x++) {
    if (Math.hypot(x - cx, y - cy) > R * HANDLE && m.at(x, y)) { m.set(x, y, 0); cut++; }
  }
  console.log(`  the lens: centre ${cx.toFixed(0)},${cy.toFixed(0)} radius ${R.toFixed(0)}; handle kept to ${HANDLE} radii (${cut} px of tail cut)`);
}

const before = m.count();
erode(m, OPEN);
const after = m.count();
const loops = contours(m).filter((p) => Math.abs(loopArea(p)) >= MIN_AREA).map((p) => simplify(p, EPS));
if (!loops.length) fail('nothing was traced');
const { d, vw: VW, vh: VH, points } = toPath(loops);

writeFileSync(
  OUT,
  `/**
 * THE SEARCH MARK — the owner's spiral glass, traced. Generated by
 * \`npm run build:searchglyph\` from scripts/assets/search-glass.jpg; do not edit
 * by hand. Drawn inline and filled with \`currentColor\`, EVEN-ODD, so that it
 * inverts with its button the way the plus and the minus do
 * (lib/cigToggleGlyph.ts) — an <img> could not.
 *
 * ${loops.length} loops, ${points} points, ${d.length} bytes of path.
 */
import type { CigGlyph } from './cigToggleGlyph';

/**
 * SIZED BY THE PLUS'S OWN RULE ("make it the same size"): the plus takes 16
 * of the 26px its button's rule leaves, 5 clear on every side. This mark is
 * wider than it is tall, so its LONG side is the 16 and the other follows.
 */
export const SEARCH_GLYPH: CigGlyph = {
  viewBox: '0 0 ${VW} ${VH}',
  transform: '',
  d: '${d}',
  fillRule: 'evenodd',
  width: ${MARK},
  height: ${+((MARK * VH) / VW).toFixed(2)},
};
`,
);

console.log(`  opened by ${OPEN}px: ink ${before} -> ${after} (${((100 * after) / before).toFixed(1)}%)`);
console.log(`  ${loops.length} loops kept, ${points} points, ${d.length} bytes of path`);
console.log(`  the mark is ${VW} x ${VH} units (${(VW / VH).toFixed(3)} wide for its height)`);
console.log(`wrote ${OUT}`);

// ---- for looking at ---------------------------------------------------------
if (process.env.GLYPH_PREVIEW) {
  mkdirSync('.tmp', { recursive: true });
  const B = 30, RULE = 2, k = MARK / Math.max(VW, VH);
  const svg = (px, fg, bg) =>
    `<svg xmlns="http://www.w3.org/2000/svg" width="${px * 8}" height="${px * 8}" viewBox="0 0 ${B} ${B}">` +
    `<rect width="${B}" height="${B}" fill="#010101"/><rect x="${RULE}" y="${RULE}" width="${B - 2 * RULE}" height="${B - 2 * RULE}" fill="${bg}"/>` +
    `<g transform="translate(${(B - VW * k) / 2} ${(B - VH * k) / 2}) scale(${k})"><path d="${d}" fill="${fg}" fill-rule="evenodd"/></g></svg>`;
  const tiles = [];
  for (const px of [21, 30, 60]) for (const [fg, bg] of [['#010101', '#ffffff'], ['#ffffff', '#010101']]) {
    const small = await sharp(Buffer.from(svg(px, fg, bg))).resize({ width: px, kernel: 'lanczos3' }).png().toBuffer();
    tiles.push(await sharp(small).resize({ width: 240, kernel: 'nearest' }).png().toBuffer());
  }
  await sharp({ create: { width: 250 * tiles.length, height: 240, channels: 3, background: '#cccccc' } })
    .composite(tiles.map((t, i) => ({ input: t, left: i * 250 + 5, top: 0 })))
    .png()
    .toFile(`.tmp/search-glyph-open${OPEN}.png`);
  console.log(`  GLYPH_PREVIEW: wrote .tmp/search-glyph-open${OPEN}.png (the button at 21 / 30 / 60 px, each both ways round)`);
}
