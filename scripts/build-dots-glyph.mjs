/**
 * Cuts the owner's three spirals into the row's DOTS mark.
 *
 *   npm run build:dotsglyph
 *
 * The owner's 2026-09-20 ask: a button "mirrored from the magnifying glass
 * button using this attached image … on press the dots will turn 90 degrees so
 * they are horizontal". The image (scripts/assets/dots.jpg) is three spiral
 * discs stacked upright, the lowest with a curling tail — the same hand as the
 * glass, and the same reason for tracing it rather than loading it: the button
 * inverts under the pointer and only an inline path filled with `currentColor`
 * can follow that. The tracing is scripts/lib/trace-mark.mjs, shared with the
 * glass.
 *
 * IT IS EMITTED LYING DOWN, and turned upright by the page. The mark is drawn
 * as a column and the owner wants it to TURN on press, so the path is written
 * with its dots in a ROW — the drawing rotated a quarter turn on the way out —
 * and the button carries `rotate(-90deg)` at rest, which it drops when it is
 * pressed. That way the open state, which is the one held for as long as the
 * menu is out, is the untransformed one, and the mark's own box is the box a
 * row of dots wants rather than a column's turned sideways.
 *
 * THE WHITE IS OPENED UP FIRST (`OPEN`), as it is for the glass and for the
 * same reason: each spiral's cut is about a fiftieth of the mark's height,
 * which at the size the row draws this is a third of a pixel, and a browser
 * antialiases that to grey. Opened, the dots read as rings.
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import sharp from 'sharp';
import { inkMask, erode, contours, loopArea, simplify, toPath } from './lib/trace-mark.mjs';

const SRC = 'scripts/assets/dots.jpg';
const OUT = 'lib/dotsGlyph.ts';

const TRACE = 1200;
/** How much black comes off every edge before tracing, in trace px. */
const OPEN = Number(process.env.GLYPH_OPEN ?? 7);
/**
 * THE MARK'S LONG SIDE AS DRAWN, and it is NOT the glass's 16.
 *
 * The plus, the minus and the glass all take 16 of the 26px their rule leaves,
 * 5 clear on every side. This mark is a COLUMN OF THREE and three times as
 * long as it is wide, so at 16 each dot comes out 4.8px across — 3.4 on screen
 * at the row's scale, which is mush. At 22 (2px clear) each dot is 6.6, and
 * the three read as three both upright and turned. Judged in the button at
 * 21 / 30 / 55px against 16, 20 and 24: 24 crowds the rule, 16 and 20 are
 * weak. The BOX is the glass's to the pixel, which is what the owner's "the
 * same properties and parameters" is about.
 */
const MARK = 22;
const EPS = 1.6;
const MIN_AREA = 60;

const fail = (m) => {
  throw new Error(`build-dots-glyph: ${m}`);
};

const m = await inkMask(SRC, { trace: TRACE, pad: OPEN + 4 });
console.log(`${SRC}: ${m.source}, traced at ${m.W0}x${m.H0}`);

const before = m.count();
erode(m, OPEN);
const after = m.count();
let loops = contours(m).filter((p) => Math.abs(loopArea(p)) >= MIN_AREA).map((p) => simplify(p, EPS));
if (!loops.length) fail('nothing was traced');

/*
 * THREE DOTS, AND THE BUILD COUNTS THEM. Each is a disc with a spiral cut out,
 * so each contributes an outer loop and an inner one, and the lowest one's
 * tail curls into a second cut: six or seven loops, in three clusters down the
 * picture. Fewer clusters and the opening has run two dots together; more and
 * something else has been traced.
 */
{
  const mid = loops.map((p) => p.reduce((s, q) => s + q[1], 0) / p.length).sort((a, b) => a - b);
  const bands = mid.reduce((acc, y) => (acc.length && y - acc[acc.length - 1].at < m.H0 * 0.12 ? acc[acc.length - 1] : acc.push({ at: y }), (acc[acc.length - 1].at = y), acc), []);
  if (bands.length !== 3) fail(`expected three dots down the picture, found ${bands.length} bands in ${loops.length} loops`);
}

// ---- lying down ------------------------------------------------------------
// a quarter turn: (x, y) -> (maxY - y, x), which puts the TAILED dot — the
// bottom one — on the left and the topmost on the right, so that the page's
// `rotate(-90deg)` (left goes to the bottom) stands the drawing back up the
// way the owner drew it. Checked by rendering the path both ways round.
{
  let maxY = -1e9;
  for (const p of loops) for (const q of p) maxY = Math.max(maxY, q[1]);
  loops = loops.map((p) => p.map(([x, y]) => [maxY - y, x]));
}

const { d, vw: VW, vh: VH, points } = toPath(loops);
if (VW < VH) fail(`the mark did not come out lying down (${VW} x ${VH})`);

writeFileSync(
  OUT,
  `/**
 * THE DOTS MARK — the owner's three spirals, traced and laid on their side.
 * Generated by \`npm run build:dotsglyph\` from scripts/assets/dots.jpg; do not
 * edit by hand. Drawn inline and filled with \`currentColor\`, EVEN-ODD, so that
 * it inverts with its button the way the plus, the minus and the glass do.
 *
 * ${loops.length} loops, ${points} points, ${d.length} bytes of path.
 *
 * IT IS STORED LYING DOWN — the dots in a row, the tailed one on the right —
 * because that is the state the menu HOLDS. The button stands it upright with
 * a \`rotate(-90deg)\` at rest and drops that on press, which is the owner's
 * "on press the dots will turn 90 degrees so they are horizontal".
 */
import type { CigGlyph } from './cigToggleGlyph';

export const DOTS_GLYPH: CigGlyph = {
  viewBox: '0 0 ${VW} ${VH}',
  transform: '',
  d: '${d}',
  fillRule: 'evenodd',
  width: ${MARK},
  height: ${+((MARK * VH) / VW).toFixed(2)},
};
`,
);

console.log(`  opened by ${OPEN}px: ink ${before} -> ${after} (${((100 * after) / before).toFixed(1)}%)`);
console.log(`  ${loops.length} loops kept, ${points} points, ${d.length} bytes of path`);
console.log(`  lying down the mark is ${VW} x ${VH} units (${(VW / VH).toFixed(2)} wide for its height)`);
console.log(`wrote ${OUT}`);

if (process.env.GLYPH_PREVIEW) {
  mkdirSync('.tmp', { recursive: true });
  const B = 30, RULE = 2, k = MARK / Math.max(VW, VH);
  const svg = (px, fg, bg, turn) =>
    `<svg xmlns="http://www.w3.org/2000/svg" width="${px * 8}" height="${px * 8}" viewBox="0 0 ${B} ${B}">` +
    `<rect width="${B}" height="${B}" fill="#010101"/><rect x="${RULE}" y="${RULE}" width="${B - 2 * RULE}" height="${B - 2 * RULE}" fill="${bg}"/>` +
    `<g transform="translate(${B / 2} ${B / 2}) rotate(${turn}) translate(${(-VW * k) / 2} ${(-VH * k) / 2}) scale(${k})">` +
    `<path d="${d}" fill="${fg}" fill-rule="evenodd"/></g></svg>`;
  const tiles = [];
  for (const turn of [-90, 0]) for (const px of [21, 30, 60]) for (const [fg, bg] of [['#010101', '#ffffff'], ['#ffffff', '#010101']]) {
    const small = await sharp(Buffer.from(svg(px, fg, bg, turn))).resize({ width: px, kernel: 'lanczos3' }).png().toBuffer();
    tiles.push(await sharp(small).resize({ width: 200, kernel: 'nearest' }).png().toBuffer());
  }
  await sharp({ create: { width: 210 * 6, height: 208 * 2, channels: 3, background: '#cccccc' } })
    .composite(tiles.map((t, i) => ({ input: t, left: (i % 6) * 210 + 5, top: Math.floor(i / 6) * 208 + 4 })))
    .png()
    .toFile(`.tmp/dots-glyph-open${OPEN}.png`);
  console.log(`  GLYPH_PREVIEW: wrote .tmp/dots-glyph-open${OPEN}.png (upright then turned, at 21 / 30 / 60 px, each both ways round)`);
}
